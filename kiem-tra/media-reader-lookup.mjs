import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const root=new URL("../",import.meta.url);
const c=vm.createContext({Map,Date,Error,String});
vm.runInContext(fs.readFileSync(new URL("android/www/reader-lookup.js",root),"utf8"),c);
let nb={},calls=0,release,time=100,fail=false;
const translator=async(word,language)=>{calls++;if(fail)throw Error("offline");if(release)await release.promise;return {meaning:language+":"+word,reading:""};};
const api=c.NeutronReaderLookup.create({getNotebook:async()=>nb,translate:translator,now:()=>time,max:2,ttl:100});
release={};release.promise=new Promise(resolve=>release.resolve=resolve);
const a=api.lookup({word:"猫",language:"ja",sentence:"blocked translation must never run"});
const b=api.lookup({word:"猫",language:"ja"});
await new Promise(r=>setTimeout(r,0));assert.equal(calls,1);
release.resolve();await Promise.all([a,b]);release=null;
assert.equal((await api.lookup({word:"猫",language:"ja"})).meaning,"ja:猫");assert.equal(calls,1);
nb={"javi:猫":{means:["nghĩa vừa sửa"],mEdit:true,reading:"ねこ",duong:{nghe:{cap:5}}}};
assert.equal((await api.lookup({word:"猫",language:"ja"})).meaning,"nghĩa vừa sửa");assert.equal(calls,1);
const before=JSON.stringify(nb);await api.lookup({word:"猫",language:"ja"});assert.equal(JSON.stringify(nb),before);
nb={"javi:猫":{means:["deleted"],del:true}};
assert.notEqual((await api.lookup({word:"猫",language:"ja"})).meaning,"deleted");
await api.lookup({word:"猫",language:"en"});assert.equal(calls,2);
await api.lookup({word:"犬",language:"ja"});assert.equal(calls,3);
await api.lookup({word:"猫",language:"ja"});assert.equal(calls,4);
time+=101;await api.lookup({word:"猫",language:"ja"});assert.equal(calls,5);
fail=true;await assert.rejects(api.lookup({word:"失敗",language:"ja"}));fail=false;
assert.equal((await api.lookup({word:"失敗",language:"ja"})).meaning,"ja:失敗");
console.log("Reader lookup: concurrent dedupe, warm cache, language isolation, edited notebook precedence, tombstone, no writes, bounded eviction, TTL and error retry OK");
